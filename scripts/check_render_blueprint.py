"""Validate safety invariants in the opt-in Render staging Blueprint."""

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
BLUEPRINT = ROOT / "render.staging.yaml"
EXPECTED_BRANCH = "chore/modernization-foundation"


def fail(message: str) -> None:
    raise SystemExit(f"Unsafe Render staging Blueprint: {message}")


def main() -> None:
    document = yaml.safe_load(BLUEPRINT.read_text(encoding="utf-8"))
    services = document.get("services", [])
    databases = document.get("databases", [])
    if len(services) != 3 or len(databases) != 1:
        fail("expected one web service, one cron job, one cache, and one database")
    for resource in [*services, *databases]:
        if "staging" not in resource.get("name", ""):
            fail("every resource name must be isolated with a staging suffix")
    git_services = [service for service in services if service["type"] != "keyvalue"]
    for service in git_services:
        if service.get("branch") != EXPECTED_BRANCH:
            fail(f"{service['name']} must target {EXPECTED_BRANCH}")
        if service.get("autoDeployTrigger") != "off":
            fail(f"{service['name']} must require manual deployment")
    web = next(service for service in services if service["type"] == "web")
    if web.get("healthCheckPath") != "/health/ready/":
        fail("web service must use dependency readiness as its deploy gate")
    env = {item["key"]: item for item in web.get("envVars", [])}
    if not env.get("DJANGO_SECRET_KEY", {}).get("generateValue"):
        fail("Django secret must be generated by Render")
    for key in (
        "DJANGO_ALLOWED_HOSTS",
        "DJANGO_CORS_ALLOWED_ORIGINS",
        "DJANGO_CSRF_TRUSTED_ORIGINS",
    ):
        if env.get(key, {}).get("sync") is not False:
            fail(f"{key} must be entered explicitly during Blueprint creation")
    print("Render staging Blueprint safety invariants valid.")


if __name__ == "__main__":
    main()
